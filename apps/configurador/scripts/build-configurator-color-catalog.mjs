import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const agamaSourceRoot = resolve(repoRoot, "..");

const EXCLUDED_SLUGS = new Set([
  "mb-105-mb-deslizante",
  "mb-200-mb-deslizante-alta-transparencia",
]);

function readJson(pathname) {
  return JSON.parse(readFileSync(pathname, "utf8"));
}

function readText(pathname) {
  return readFileSync(pathname, "utf8");
}

function slugify(value) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function deriveFamily(name, finish) {
  const value = `${name} ${finish ?? ""}`.toLowerCase();
  if (value.includes("amarillo")) return "amarillos";
  if (value.includes("azul")) return "azules";
  if (value.includes("verde")) return "verdes";
  if (value.includes("naranja")) return "naranjas";
  if (value.includes("rojo")) return "rojos";
  if (value.includes("rosa")) return "rosas";
  if (value.includes("morado") || value.includes("violeta")) return "morados";
  if (value.includes("negro")) return "negros";
  if (value.includes("blanco")) return "blancos";
  if (value.includes("gris") || value.includes("plata")) return "grises";
  if (value.includes("natural") || value.includes("beige")) return "naturales";
  if (value.includes("transpar")) return "transparentes";
  if (value.includes("cafe") || value.includes("café") || value.includes("chocolate")) return "cafes";
  if (value.includes("ambar") || value.includes("ámbar")) return "ambar";
  if (value.includes("aluminio") || value.includes("metal")) return "metalicos";
  return "grises";
}

function extractCards(html, line) {
  const matches = [...html.matchAll(/href="\/productos\/(?:masterbatch|pigmentos)\/([^"/]+)\/"[\s\S]*?<h3[^>]*>(.*?)<\/h3>/g)];

  return matches.map((match) => {
    const slug = match[1].trim();
    const rawHeading = match[2].replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
    const codeMatch = rawHeading.match(/^([A-Z]{1,3}-\d{3})\s+(.*)$/i);
    const code = codeMatch?.[1]?.toUpperCase() ?? rawHeading.split(" ")[0].toUpperCase();
    const name = codeMatch?.[2]?.trim() ?? rawHeading;
    return { slug, code, name, line };
  });
}

const masterbatchHtml = readText(join(agamaSourceRoot, "productos", "masterbatch", "index.html"));
const pigmentosHtml = readText(join(agamaSourceRoot, "productos", "pigmentos", "index.html"));
const sheetManifest = readJson(join(agamaSourceRoot, "data", "tech-sheets-manifest.json"));
const imageManifest = readJson(join(agamaSourceRoot, "data", "product-images-manifest.json"));

const sheetsBySlug = new Map(sheetManifest.filter((entry) => entry?.slug).map((entry) => [entry.slug, entry]));
const imagesBySlug = new Map(imageManifest.filter((entry) => entry?.slug).map((entry) => [entry.slug, entry]));

const catalog = [...extractCards(masterbatchHtml, "masterbatch"), ...extractCards(pigmentosHtml, "pigmentos")]
  .filter((entry) => !EXCLUDED_SLUGS.has(entry.slug))
  .map((entry) => {
    const sheet = sheetsBySlug.get(entry.slug) ?? null;
    const image = imagesBySlug.get(entry.slug) ?? null;
    const finish = sheet?.title?.match(/\b(Transparente|Opaco|Perlado|Fluorescente)\b/i)?.[1] ?? null;
    const swatchAssetUrl = image?.cover?.publicUrl ?? null;

    return {
      code: entry.code,
      name: entry.name,
      family: deriveFamily(entry.name, finish),
      hex: null,
      validationStatus: "pending",
      line: entry.line,
      slug: entry.slug || slugify(`${entry.code}-${entry.name}`),
      finish,
      swatchAssetUrl,
      swatchSource: swatchAssetUrl ? "product-image" : null,
      sourceSheetUrl: sheet?.fileUrl ?? null,
      sourceImageUrl: swatchAssetUrl,
    };
  })
  .sort((a, b) => a.code.localeCompare(b.code, "es"));

const families = [...new Set(catalog.map((entry) => entry.family))];

const output = `import type { AgamaColorGenerated, AgamaColorFamily } from "@/lib/configurator-types";

// This file is generated by scripts/build-configurator-color-catalog.mjs.
// It reads the AGAMA source exports from the sibling repository workspace.
export const GENERATED_AGAMA_COLORS: AgamaColorGenerated[] = ${JSON.stringify(catalog, null, 2)} as AgamaColorGenerated[];

export const GENERATED_AGAMA_COLOR_FAMILY_ORDER: AgamaColorFamily[] = ${JSON.stringify(families, null, 2)} as AgamaColorFamily[];
`;

writeFileSync(join(repoRoot, "src", "data", "agama-colors.generated.ts"), output);

console.log(
  JSON.stringify(
    {
      total: catalog.length,
      withSwatch: catalog.filter((entry) => entry.swatchAssetUrl).length,
      excludedSlugs: [...EXCLUDED_SLUGS],
    },
    null,
    2,
  ),
);
